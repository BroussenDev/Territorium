export type LexiconKind = keyof Lexicon;

/** Every language's words of one kind. */
export function lexiconWords(
  kind: LexiconKind,
  source: Record<string, Lexicon> = LEXICONS,
): string[] {
  return Object.values(source).flatMap((l) => l[kind] ?? []);
}
